#!/usr/bin/env python3
"""Generate src/input/tables.rs from the XNAMn subroutines of the original datcom.f.

Usage: gen_namelist_tables.py <path/to/datcom.f> > src/input/tables.rs

Each XNAMn routine holds DATA tables describing one namelist: its name, the
variable names, per-variable name length (LEN*), dimension (LDM*, negative =
logical) and offset into the backing common-block array (LOC*).  The tables are
extracted mechanically so that they match the original exactly.
"""

import re
import sys


def logical_lines(text):
    """Strip comments and join '&' continuation lines."""
    out, cur = [], ""
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("!"):
            continue
        body = line
        if cur or body.lstrip().startswith("&"):
            body = body.lstrip()
            if body.startswith("&"):
                body = body[1:]
        if body.endswith("&"):
            cur += body[:-1]
            continue
        out.append(cur + body)
        cur = ""
    if cur:
        out.append(cur)
    return out


def parse_values(s):
    """Parse a DATA value list: 4Hx tokens, n*v repeats, plain integers."""
    vals = []
    for tok in s.split(","):
        t = tok.lstrip()
        if not t.strip():
            continue
        m = re.match(r"(\d+)\*(.*)$", t.strip())
        rep, body = (int(m.group(1)), m.group(2)) if m else (1, t)
        if re.match(r"\d+H", body):
            v = body[2:3] if len(body) > 2 else " "
        else:
            v = int(body.strip())
        vals.extend([v] * rep)
    return vals


def parse_xnam(lines):
    data = {}
    for ln in lines:
        s = ln.strip()
        if s.upper().startswith("DATA"):
            for m in re.finditer(r"(\w+)\s*/([^/]*)/", s[4:]):
                data[m.group(1).upper()] = parse_values(m.group(2))
    call = next(line for line in lines if "CALL NAMER(" in line)
    inner = call[call.index("CALL NAMER(") + len("CALL NAMER(") :].rsplit(")", 1)[0]
    args = [a.strip() for a in inner.split(",")]
    maxcom = int(args[10])
    name = "".join(data["NLNAME"]).strip()
    lens = data[args[6].upper()]
    ldms = data[args[8].upper()]
    locs = data[args[11].upper()]
    chars = data[args[4].upper()]
    names, pos = [], 0
    for n in lens:
        names.append("".join(chars[pos : pos + n]).strip())
        pos += n
    assert pos == len(chars), (name, pos, len(chars))
    assert len(names) == len(ldms) == len(locs), name
    return name, maxcom, list(zip(names, ldms, locs))


def main():
    src = open(sys.argv[1], encoding="latin-1").read().splitlines()
    starts = [
        i for i, line in enumerate(src) if re.match(r"\s+SUBROUTINE XNAM\d+\(", line)
    ]
    ends = starts[1:] + [len(src)]
    result = []
    for s, e in zip(starts, ends):
        num = int(re.search(r"XNAM(\d+)", src[s]).group(1))
        name, maxcom, vars_ = parse_xnam(logical_lines("\n".join(src[s:e])))
        result.append((num, name, maxcom, vars_))
    result.sort()
    print(
        "// @generated by tools/gen_namelist_tables.py from the XNAMn routines of datcom.f."
    )
    print("// Do not edit by hand.\n")
    print("use super::{NamelistDef, VarDef};\n")
    print("/// All namelists, in the order of the original XNAM1..XNAM23 routines.")
    print("pub static NAMELISTS: &[NamelistDef] = &[")
    for num, name, maxcom, vars_ in result:
        print(f"    // XNAM{num}")
        print(f'    NamelistDef {{ name: "{name}", size: {maxcom}, vars: &[')
        for vn, ldm, loc in vars_:
            print(
                f'        VarDef {{ name: "{vn}", dim: {abs(ldm)}, logical: '
                f"{str(ldm < 0).lower()}, loc: {loc} }},"
            )
        print("    ] },")
    print("];")


main()
